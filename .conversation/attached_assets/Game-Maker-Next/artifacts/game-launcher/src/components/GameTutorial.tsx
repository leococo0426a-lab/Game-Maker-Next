export function GameTutorial({ gameId }: { gameId: string }) {
  const [open, setOpen] = useState(false);
  const lines = GAME_INSTRUCTIONS[gameId] || [
    "このゲームのルールは簡単！",
    "画面をクリックしてプレイ開始",
    "スコアを競ってランクインを目指そう",
  ];

  return (
    <>
      <button
        onClick={() => setOpen(true)}
        className="flex items-center gap-1 text-xs font-bold px-2 py-1 rounded-lg text-muted-foreground hover:text-foreground hover:bg-muted transition-colors"
      >
        <HelpCircle className="w-3.5 h-3.5" />
        <span className="hidden sm:inline">遊び方</span>
      </button>

      {open && (
        <div className="fixed inset-0 z-[100] flex items-center justify-center p-4">
          <div className="absolute inset-0 bg-black/40 backdrop-blur-sm" onClick={() => setOpen(false)} />
          <div className="relative bg-white rounded-2xl shadow-2xl max-w-md w-full p-6 space-y-4 animate-in fade-in zoom-in-95 duration-200">
            <div className="flex items-center justify-between">
              <h3 className="text-lg font-black text-foreground flex items-center gap-2">
                <HelpCircle className="w-5 h-5 text-primary" />
                遊び方
              </h3>
              <button onClick={() => setOpen(false)} className="text-muted-foreground hover:text-foreground p-1 rounded-lg hover:bg-muted transition-colors">
                <X className="w-5 h-5" />
              </button>
            </div>
            <div className="space-y-2">
              {lines.map((line, i) => (
                <div key={i} className="flex items-start gap-2 text-sm">
                  <div className="flex-shrink-0 w-5 h-5 rounded-full bg-primary/10 text-primary flex items-center justify-center text-xs font-bold mt-0.5">
                    {i + 1}
                  </div>
                  <p className="text-foreground leading-relaxed">{line}</p>
                </div>
              ))}
            </div>
            <Button onClick={() => setOpen(false)} className="w-full rounded-full">
              <ChevronRight className="w-4 h-4 mr-1" />
              プレイ開始！
            </Button>
          </div>
        </div>
      )}
    </>
  );
}
