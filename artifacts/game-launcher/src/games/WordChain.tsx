export default function WordChain() {
  const [history, setHistory] = useState<string[]>(["りんご"]);
  const [input, setInput] = useState("");
  const [message, setMessage] = useState("");
  const [gameOver, setGameOver] = useState(false);
  const [turn, setTurn] = useState(0);
  const { addPlay } = useGameHistory();

  const lastWord = history[history.length - 1];
  const lastChar = lastWord.slice(-1);
  const needsLong = lastChar === "ん";

  const aiMove = useCallback(() => {
    const words = WORDS[lastChar] || [];
    const valid = words.filter(w => !history.includes(w));
    if (valid.length === 0) {
      setMessage("私の負け... あなたの勝ち！");
      setGameOver(true);
      addPlay("wordchain", history.length);
      return;
    }
    const word = valid[Math.floor(Math.random() * valid.length)];
    setHistory(prev => [...prev, word]);
    setTurn(t => t + 1);
    if (word.slice(-1) === "ん") {
      setMessage(`アイが「ん」で終わった！あなたの勝ち！`);
      setGameOver(true);
      addPlay("wordchain", history.length);
    }
  }, [lastChar, history, addPlay]);

  const handleSubmit = () => {
    if (gameOver || !input.trim()) return;
    const w = input.trim();
    if (w[0] !== lastChar) { setMessage(`「${lastChar}」から始まる単語を入力して！`); return; }
    if (history.includes(w)) { setMessage("その単語はもう使われた！"); return; }
    if (w.slice(-1) === "ん") { setMessage("「ん」で終わる単語はダメ！"); return; }

    setHistory(prev => [...prev, w]);
    setInput("");
    setMessage("");
    setTimeout(aiMove, 800);
  };

  const reset = () => {
    setHistory(["りんご"]);
    setInput("");
    setMessage("");
    setGameOver(false);
    setTurn(0);
  };

  return (
    <div className="flex flex-col items-center space-y-4 max-w-sm mx-auto">
      <div className="text-center">
        <p className="text-sm font-bold text-muted-foreground">次は「<span className="text-2xl text-primary font-black">{needsLong ? "ん" : lastChar}</span>」{needsLong ? "で終わりっぽい..." : "から"}</p>
        <p className="text-xs text-muted-foreground">回数: {history.length - 1}</p>
      </div>
      {message && <p className="font-black text-lg text-primary text-center">{message}</p>}
      <div className="w-full bg-muted rounded-xl p-3 max-h-48 overflow-y-auto space-y-1">
        {history.map((w, i) => (
          <div key={i} className={`text-sm px-2 py-1 rounded ${i % 2 === 0 ? "bg-primary/10 text-primary" : "bg-secondary text-secondary-foreground"}`}>
            {i % 2 === 0 ? "AI" : "あなた"}: {w}
          </div>
        ))}
      </div>
      <div className="flex gap-2 w-full">
        <Input value={input} onChange={e => setInput(e.target.value)} placeholder={`${needsLong ? "ん" : lastChar}から始まる単語...`} maxLength={10} className="rounded-xl text-center font-bold" onKeyDown={e => e.key === "Enter" && handleSubmit()} />
        <Button onClick={handleSubmit} disabled={gameOver} className="rounded-xl px-4">回答</Button>
      </div>
      <Button variant="outline" onClick={reset} className="rounded-full">もう一度</Button>
    </div>
  );
}
